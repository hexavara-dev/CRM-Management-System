import { cn } from "@/lib/utils";

const ALLOWED_TAGS = new Set([
  "strong",
  "b",
  "em",
  "i",
  "u",
  "ul",
  "ol",
  "li",
  "br",
  "div",
  "p",
]);

function escapeHtml(value: string) {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/\"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

function decodeCommonEntities(value: string) {
  return value
    .replace(/&nbsp;/gi, " ")
    .replace(/&quot;/gi, '"')
    .replace(/&#039;/gi, "'")
    .replace(/&lt;/gi, "<")
    .replace(/&gt;/gi, ">")
    .replace(/&amp;/gi, "&");
}

function stripUnsafeTags(value: string) {
  return value.replace(/<\/?([a-z0-9]+)(?:\s[^>]*)?>/gi, (full, tag: string) => {
    const normalized = tag.toLowerCase();
    if (!ALLOWED_TAGS.has(normalized)) return "";
    return full.startsWith("</") ? `</${normalized}>` : `<${normalized}>`;
  });
}

export function normalizeRichText(value: string) {
  if (!value) return "";
  // Existing projects may contain plain text. Escape it before rendering so
  // only content generated by this editor is interpreted as formatting.
  if (!/<\/?(?:strong|b|em|i|u|ul|ol|li|br|div|p)(?:\s[^>]*)?>/i.test(value)) {
    return escapeHtml(decodeCommonEntities(value)).replace(/\r?\n/g, "<br>");
  }
  return stripUnsafeTags(value);
}

/** Sanitizes HTML already produced by contentEditable without escaping it twice. */
export function sanitizeRichTextHtml(value: string) {
  return stripUnsafeTags(value);
}

export function RichTextContent({
  value,
  className,
}: {
  value: string;
  className?: string;
}) {
  return (
    <div
      className={cn("[&_ol]:list-decimal [&_ol]:pl-5 [&_ul]:list-disc [&_ul]:pl-5", className)}
      dangerouslySetInnerHTML={{ __html: normalizeRichText(value) }}
    />
  );
}
